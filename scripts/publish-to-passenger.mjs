#!/usr/bin/env node
/**
 * Point Passenger at the build we just produced.
 *
 * WHY THIS EXISTS
 * ---------------
 * growcdx.com serves traffic through Passenger:
 *
 *   PassengerAppRoot     /home/u454713534/domains/growcdx.com/nodejs
 *   PassengerStartupFile server.js
 *   PassengerRestartDir  /home/u454713534/domains/growcdx.com/nodejs/tmp
 *
 * The host's deploy pipeline builds the repo in
 * <domain>/hbuilds/source/repository and copies the build output into
 * <domain>/public_html. Nothing in it writes to <domain>/nodejs. That
 * directory was last written on 2026-06-24 by a one-off archive upload, so
 * every git deploy since has built correctly, reported success, and left the
 * process serving traffic running the June app. That is why a section removed
 * from /about was still live, /portfolio 404'd, and /api/health 404'd while
 * appearing in every build.
 *
 * WHAT IT DOES
 * ------------
 * Replaces <domain>/nodejs/server.js with a one-line shim that loads the
 * freshly built repository's server.js, then touches tmp/restart.txt so
 * Passenger restarts onto it. No large copy: the shim resolves through to the
 * build directory, which already holds node_modules and .next.
 *
 * Node resolves a required file to its real path, so __dirname inside the real
 * server.js is the build repository — its apps/grow lookups stay correct.
 *
 * This is a workaround for a host pipeline that no longer syncs the app root.
 * The clean fix is to have the Node.js application re-provisioned in hPanel so
 * the platform owns that sync again; until then this keeps deploys honest.
 *
 * Safe by construction: no-ops anywhere the layout isn't present (local
 * machines, CI), and never fails the build.
 */
import { existsSync, mkdirSync, writeFileSync, copyFileSync, readFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";

const log = (s) => console.log(`[publish] ${s}`);

function findDomainDir(start) {
  let dir = start;
  for (let i = 0; i < 8; i++) {
    if (existsSync(join(dir, "nodejs")) && existsSync(join(dir, "public_html"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  return null;
}

try {
  const repoRoot = process.cwd();
  const realServer = join(repoRoot, "server.js");

  if (!existsSync(realServer)) {
    log("no server.js in the build — nothing to publish.");
    process.exit(0);
  }

  const domainDir = findDomainDir(repoRoot);
  if (!domainDir) {
    log("not a Hostinger domain layout (no sibling nodejs/ + public_html/) — skipping.");
    process.exit(0);
  }

  const appRoot = join(domainDir, "nodejs");
  const target = join(appRoot, "server.js");
  const shim =
    "// Generated by scripts/publish-to-passenger.mjs — do not edit.\n" +
    "// Passenger boots this file; it hands off to the current build.\n" +
    `module.exports = require(${JSON.stringify(realServer)});\n`;

  // Keep one copy of whatever was here before we ever touched it.
  const backup = join(appRoot, "server.js.pre-publish.bak");
  if (existsSync(target) && !existsSync(backup)) {
    try {
      copyFileSync(target, backup);
      log(`backed up the previous server.js (${statSync(target).mtime.toISOString()}) -> ${backup}`);
    } catch (err) {
      log(`could not back up the previous server.js: ${err.message}`);
    }
  }

  let current = null;
  try {
    current = readFileSync(target, "utf8");
  } catch {
    /* absent is fine */
  }

  if (current === shim) {
    log("shim already current.");
  } else {
    writeFileSync(target, shim);
    log(`wrote shim -> ${target}`);
    log(`   pointing at ${realServer}`);
  }

  // Passenger restarts the app when this file's mtime changes.
  const restartDir = join(appRoot, "tmp");
  mkdirSync(restartDir, { recursive: true });
  writeFileSync(join(restartDir, "restart.txt"), new Date().toISOString());
  log("touched tmp/restart.txt — Passenger will restart onto the new build.");
} catch (err) {
  // A failure here must never fail the deploy; it just leaves the old app up.
  log(`skipped (${err && err.message})`);
}

process.exit(0);
